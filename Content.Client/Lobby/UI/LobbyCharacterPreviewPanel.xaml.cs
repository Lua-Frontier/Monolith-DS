using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control
{
    [Dependency] private IEntityManager _entManager = default!;

    public Button CharacterSetupButton => CharacterSetup;

    private EntityUid? _previewDummy;

    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
// LuaM-start
        var parent = BalanceRow.Parent!;
        var index = BalanceRow.GetPositionInParent();
        var strip = new Content.Client._LuaM.UserInterface.Hud.HudCallout { Status = Content.Client._LuaM.UserInterface.Hud.HudStatus.Nominal };
        strip.SetContent(BalanceRow);
        parent.AddChild(strip);
        strip.SetPositionInParent(index);
// LuaM-end
    }

    public void SetLoaded(bool value)
    {
        Loaded.Visible = value;
        Unloaded.Visible = !value;
    }

    public void SetSummaryText(string value)
    {
        Summary.Text = value;
    }

    // Frontier: show bank balance on character selection.
    public void SetBankBalanceText(string value)
    {
        BankBalance.Text = value;
    }
    // End Frontier

    // Company Display
    public void SetCompanyText(string value)
    {
        if (string.IsNullOrEmpty(value))
        {
            Company.SetMessage(string.Empty);
            return;
        }

        Company.SetMessage(FormattedMessage.FromMarkupPermissive(value));
    }
    // End Company Display

    // MonoCoins Display
    public void SetMonoCoinsText(string value)
    {
        MonoCoins.Text = value;
    }
    // End MonoCoins Display

    public void SetSprite(EntityUid uid)
    {
        if (_previewDummy != null)
        {
            _entManager.DeleteEntity(_previewDummy);
        }

        _previewDummy = uid;

        ViewBox.RemoveAllChildren();
        var spriteView = new SpriteView
        {
            OverrideDirection = Direction.South,
            Scale = new Vector2(5f, 5f), // LuaM
            MaxSize = new Vector2(160, 160), // LuaM
            Stretch = SpriteView.StretchMode.Fill,
        };
        spriteView.SetEntity(uid);
        ViewBox.AddChild(spriteView);
    }
}
