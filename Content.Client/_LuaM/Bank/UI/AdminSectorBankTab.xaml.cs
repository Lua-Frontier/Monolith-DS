using Content.Shared._LuaM.Bank;
using Content.Shared._NF.Bank;
using Content.Shared._NF.Bank.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._LuaM.Bank.UI;

/// <summary>
/// Admin panel tab with the faction station accounts: balances, income, adding and taking money.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AdminSectorBankTab : Control
{
    [Dependency] private IEntityManager _entMan = default!;

    /// <summary>
    /// How often the balances refresh while the tab is open, they grow every 10 seconds.
    /// </summary>
    private static readonly TimeSpan RefreshInterval = TimeSpan.FromSeconds(5);

    private static readonly Color ErrorColor = Color.FromHex("#FF8080");

    private readonly Dictionary<SectorBankAccount, AccountRow> _rows = new();
    private AdminSectorBankSystem? _system;
    private TimeSpan _sinceRefresh;

    public AdminSectorBankTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        StatusLabel.FontColorOverride = ErrorColor;
        RefreshButton.OnPressed += _ => Refresh();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _system = _entMan.System<AdminSectorBankSystem>();
        _system.StateReceived += OnState;
        Refresh();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        if (_system != null)
            _system.StateReceived -= OnState;
        _system = null;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!VisibleInTree)
            return;

        _sinceRefresh += TimeSpan.FromSeconds(args.DeltaSeconds);
        if (_sinceRefresh >= RefreshInterval)
            Refresh();
    }

    private void Refresh()
    {
        _sinceRefresh = TimeSpan.Zero;
        _system?.RequestState();
    }

    private void OnState(AdminSectorBankStateEvent ev)
    {
        StatusLabel.Visible = ev.Error != null;
        StatusLabel.Text = ev.Error ?? string.Empty;

        if (_rows.Count == 0)
            AddHeader();

        foreach (var account in ev.Accounts)
        {
            if (!_rows.TryGetValue(account.Account, out var row))
            {
                row = AddRow(account.Account);
                _rows[account.Account] = row;
            }

            row.Balance.Text = BankSystemExtensions.ToSpesoString(account.Balance);
            row.Income.Text = Loc.GetString("luam-admin-bank-income",
                ("amount", BankSystemExtensions.ToSpesoString((long) account.IncreasePerSecond * 3600)));
        }
    }

    private void AddHeader()
    {
        AccountsGrid.AddChild(new Label { Text = Loc.GetString("luam-admin-bank-column-account") });
        AccountsGrid.AddChild(new Label { Text = Loc.GetString("luam-admin-bank-column-balance") });
        AccountsGrid.AddChild(new Label { Text = Loc.GetString("luam-admin-bank-column-income") });
        AccountsGrid.AddChild(new Label { Text = Loc.GetString("luam-admin-bank-column-amount") });
        AccountsGrid.AddChild(new Control());
        AccountsGrid.AddChild(new Control());
    }

    private AccountRow AddRow(SectorBankAccount account)
    {
        var balance = new Label();
        var income = new Label();
        var amount = new LineEdit
        {
            MinWidth = 120,
            PlaceHolder = Loc.GetString("luam-admin-bank-amount-placeholder"),
        };
        var deposit = new Button { Text = Loc.GetString("luam-admin-bank-deposit") };
        var withdraw = new Button { Text = Loc.GetString("luam-admin-bank-withdraw") };

        deposit.OnPressed += _ => Change(account, amount, 1);
        withdraw.OnPressed += _ => Change(account, amount, -1);

        AccountsGrid.AddChild(new Label { Text = Loc.GetString($"ledger-tab-{account}"), HorizontalExpand = true });
        AccountsGrid.AddChild(balance);
        AccountsGrid.AddChild(income);
        AccountsGrid.AddChild(amount);
        AccountsGrid.AddChild(deposit);
        AccountsGrid.AddChild(withdraw);

        return new AccountRow(balance, income);
    }

    private void Change(SectorBankAccount account, LineEdit amountEdit, int sign)
    {
        if (!int.TryParse(amountEdit.Text.Trim(), out var amount) || amount <= 0)
        {
            StatusLabel.Text = Loc.GetString("luam-admin-bank-error-amount");
            StatusLabel.Visible = true;
            return;
        }

        amountEdit.Text = string.Empty;
        _system?.Change(account, amount * sign);
    }

    private sealed record AccountRow(Label Balance, Label Income);
}
