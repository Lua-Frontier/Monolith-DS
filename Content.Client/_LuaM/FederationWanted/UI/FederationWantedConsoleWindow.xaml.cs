using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._LuaM.FederationWanted;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._LuaM.FederationWanted.UI;

[GenerateTypedNameReferences]
public sealed partial class FederationWantedConsoleWindow : FancyWindow
{
    public FederationWantedConsoleWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateEntries(List<FederationWantedEntry> entries)
    {
        EmptyLabel.Visible = entries.Count == 0;
        EntriesContainer.RemoveAllChildren();

        foreach (var entry in entries)
        {
            EntriesContainer.AddChild(CreateEntry(entry));
        }
    }

    private static PanelContainer CreateEntry(FederationWantedEntry entry)
    {
        var name = new RichTextLabel();
        name.SetMarkup(Loc.GetString("federation-wanted-console-name",
            ("name", FormattedMessage.EscapeText(entry.Name))));

        var reward = new RichTextLabel();
        reward.SetMarkup(Loc.GetString("federation-wanted-console-reward", ("reward", entry.Reward)));

        var description = new RichTextLabel();
        description.SetMarkup(Loc.GetString("federation-wanted-console-description"));

        var column = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(6),
        };
        column.AddChild(name);
        column.AddChild(reward);
        column.AddChild(description);

        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(10, 10, 10, 0),
        };
        panel.AddStyleClass("AngleRect");
        panel.AddChild(column);
        return panel;
    }
}
