{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IResourceManager _resources = default!;
    [Dependency] private IUserInterfaceManager _ui = default!;

    private const string FavoritesCategoryId = "Favorites";
    private const string CustomCategoryId = "Custom";
    private const string StarIcon = "/Textures/Interface/NavMap/beveled_star.png";
    private const string EditIcon = "/Textures/Interface/VerbIcons/settings.svg.192dpi.png";

    private static readonly TimeSpan ReloadCooldown = TimeSpan.FromMilliseconds(250);
    private static readonly TimeSpan CooldownUpdateCooldown = TimeSpan.FromMilliseconds(100);
    private static readonly Color DisabledModulate = Color.White.WithAlpha(0.6f);

    private readonly SpriteSystem _sprite;
    private readonly SharedInteractionSystem _interaction;
    private readonly MobStateSystem _mobState;

    private readonly Dictionary<float, bool> _rangeCache = new();
    private readonly HashSet<string> _openedCategories = new();
    private readonly Dictionary<string, Collapsible> _categoryControls = new();
    private readonly Dictionary<string, (Button Button, string Tooltip)> _interactionButtons = new();
    private readonly Dictionary<string, string> _interactionNames = new();
    private readonly Dictionary<string, string> _categoryNames = new();
    private readonly HashSet<string> _favorites = new();
    private readonly List<RpCustomEmote> _customEmotes;
    private readonly List<RpCustomEmote> _availableCustomEmotes = new();

    private TimeSpan _lastInteractionUpdate = TimeSpan.Zero;
    private TimeSpan _lastCooldownUpdate = TimeSpan.Zero;
    private TimeSpan _cooldownEnd = TimeSpan.Zero;
    private EntityUid? _currentUser;
    private EntityUid? _currentTarget;
    private List<string> _currentInteractions = new();
    private bool _hasInitializedCategories;
    private bool _reloadQueued;
    private bool _incapacitated;
    private RpCustomEmoteWindow? _editor;

    public event Action<string, bool>? OnSendEmote;
    public event Action<RpCustomEmote, bool>? OnSendCustomEmote;

    public RpPanelWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entManager.System<SpriteSystem>();
        _interaction = _entManager.System<SharedInteractionSystem>();
        _mobState = _entManager.System<MobStateSystem>();

        TargetView.OverrideDirection = Direction.South;

        SearchInput.OnTextChanged += _ =>
        {
            ClearSearchButton.Disabled = string.IsNullOrWhiteSpace(SearchInput.Text);
            ReloadInteractionsIfNeeded(true);
        };
        ClearSearchButton.OnPressed += _ => SearchInput.Text = string.Empty;
        ClearSearchButton.Disabled = true;

        ExpandAllButton.OnPressed += _ => SetAllCategoriesExpanded(true);
        CollapseAllButton.OnPressed += _ => SetAllCategoriesExpanded(false);

        LungeToggle.Pressed = _cfg.GetCVar(LuaMCVars.RpLungeEnabled);
        LungeToggle.OnToggled += args =>
        {
            _cfg.SetCVar(LuaMCVars.RpLungeEnabled, args.Pressed);
            _cfg.SaveToFile();
        };

        foreach (var id in _cfg.GetCVar(LuaMCVars.RpFavoriteInteractions).Split(',', StringSplitOptions.RemoveEmptyEntries))
            _favorites.Add(id);

        _customEmotes = RpCustomEmoteStorage.Load(_resources, _prototypeManager);
        CreateEmoteButton.OnPressed += _ => OpenEditor(null);
        UpdateCreateEmoteButton();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _editor?.Close();
    }

    public void SetTarget(NetEntity user, NetEntity target)
    {
        _currentInteractions.Clear();
        _openedCategories.Clear();
        _hasInitializedCategories = false;

        if (!_entManager.TryGetEntity(user, out var userUid) || !_entManager.TryGetEntity(target, out var targetUid))
        {
            _currentUser = null;
            _currentTarget = null;
            TargetView.SetEntity(null);
            HeaderLabel.Text = string.Empty;
            HeaderLabel.ToolTip = null;
            _incapacitated = false;
            _availableCustomEmotes.Clear();
            ReloadInteractions(new List<RpInteractionPrototype>());
            return;
        }

        _currentUser = userUid;
        _currentTarget = targetUid;
        TargetView.SetEntity(_currentTarget);

        var targetName = Identity.Name(_currentTarget.Value, _entManager, _currentUser.Value);
        HeaderLabel.Text = targetName;
        HeaderLabel.ToolTip = Loc.GetString("rp-panel-header", ("target", targetName));

        ReloadInteractionsIfNeeded(true);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!IsOpen)
            return;

        UpdateCooldowns();
        ReloadInteractionsIfNeeded();

        if (_editor is { IsOpen: true } && _editor.Parent == Parent &&
            _editor.GetPositionInParent() < GetPositionInParent())
        {
            // --  нельзя менять порядок окон, пока движок обходит их в FrameUpdate, иначе краш
            _ui.DeferAction(() => _editor?.MoveToFront());
        }
    }

    private void UpdateCooldowns(bool force = false)
    {
        var now = _timing.CurTime;
        if (!force && _lastCooldownUpdate + CooldownUpdateCooldown > now)
            return;

        _lastCooldownUpdate = now;

        var onCooldown = _cooldownEnd > now;
        var seconds = Math.Max(1, (int) Math.Ceiling((_cooldownEnd - now).TotalSeconds));

        foreach (var (button, tooltip) in _interactionButtons.Values)
        {
            button.Disabled = onCooldown;
            button.Modulate = onCooldown ? DisabledModulate : Color.White;
            button.ToolTip = onCooldown
                ? Loc.GetString("rp-panel-interaction-cooldown-tooltip", ("seconds", seconds))
                : tooltip;
        }
    }

    private void ReloadInteractionsIfNeeded(bool force = false)
    {
        if (!_currentUser.HasValue || !_currentTarget.HasValue)
            return;

        force |= _reloadQueued;
        _reloadQueued = false;

        var now = _timing.CurTime;
        if (!force && now < _lastInteractionUpdate + ReloadCooldown)
            return;

        _lastInteractionUpdate = now;

        var interactions = GetAvailableInteractions(_currentUser.Value, _currentTarget.Value);
        var interactionIds = interactions
            .Select(interaction => interaction.ID)
            .ToList();

        interactionIds.Sort();
        interactionIds.AddRange(_availableCustomEmotes.Select(GetCustomEmoteKey));

        if (!force && _currentInteractions.SequenceEqual(interactionIds))
            return;

        _currentInteractions = interactionIds;
        ReloadInteractions(interactions);
    }

    private List<RpInteractionPrototype> GetAvailableInteractions(EntityUid user, EntityUid target)
    {
        var searchText = SearchInput.Text.Trim();
        var interactions = new List<RpInteractionPrototype>();

        _rangeCache.Clear();
        _availableCustomEmotes.Clear();
        _incapacitated = _mobState.IsIncapacitated(user) || _mobState.IsIncapacitated(target);
        if (_incapacitated)
            return interactions;

        foreach (var interaction in _prototypeManager.EnumeratePrototypes<RpInteractionPrototype>())
        {
            if (!IsInteractionAvailable(user, target, interaction))
                continue;

            if (!InteractionMatchesSearch(interaction, searchText))
                continue;

            interactions.Add(interaction);
        }

        foreach (var emote in _customEmotes)
        {
            if (emote.Self != (user == target) || emote.Message.Length == 0)
                continue;

            if (!IsInRange(user, target, RpCustomEmote.Range))
                continue;

            if (searchText.Length > 0 && !emote.Name.Contains(searchText, StringComparison.CurrentCultureIgnoreCase))
                continue;

            _availableCustomEmotes.Add(emote);
        }

        return interactions;
    }

    private bool IsInteractionAvailable(EntityUid user, EntityUid target, RpInteractionPrototype interaction)
    {
        if ((user == target ? interaction.SelfMessages : interaction.Messages) == null)
            return false;

        return IsInRange(user, target, interaction.Range)
               && CheckRequirements(user, interaction.UserRequirements)
               && CheckRequirements(target, interaction.TargetRequirements);
    }

    private void ReloadInteractions(List<RpInteractionPrototype> interactions)
    {
        ButtonsContainer.DisposeAllChildren();
        _categoryControls.Clear();
        _interactionButtons.Clear();

        var interactionsByCategory = interactions
            .GroupBy(interaction => interaction.Category.Id)
            .ToDictionary(
                group => group.Key,
                group => group.OrderBy(GetInteractionName).ToList());

        var openFirstCategory = !_hasInitializedCategories && string.IsNullOrWhiteSpace(SearchInput.Text);

        var favorites = interactions.Where(interaction => _favorites.Contains(interaction.ID)).OrderBy(GetInteractionName).ToList();
        var customFavorites = _availableCustomEmotes.Where(emote => emote.Favorite).ToList();
        if (favorites.Count + customFavorites.Count > 0)
        {
            var grid = AddCategory(FavoritesCategoryId, Loc.GetString("rp-panel-favorites-category-name"),
                favorites.Count + customFavorites.Count, ref openFirstCategory);

            foreach (var interaction in favorites)
                grid.AddChild(PrepareInteractionButton(interaction, FavoritesCategoryId));

            foreach (var emote in customFavorites)
                grid.AddChild(PrepareCustomEmoteButton(emote, FavoritesCategoryId));
        }

        if (_availableCustomEmotes.Count > 0)
        {
            var grid = AddCategory(CustomCategoryId, Loc.GetString("rp-panel-custom-category-name"),
                _availableCustomEmotes.Count, ref openFirstCategory);

            foreach (var emote in _availableCustomEmotes)
                grid.AddChild(PrepareCustomEmoteButton(emote, CustomCategoryId));
        }

        foreach (var category in _prototypeManager.EnumeratePrototypes<RpInteractionCategoryPrototype>().OrderBy(category => category.Order))
        {
            if (!interactionsByCategory.TryGetValue(category.ID, out var categoryInteractions))
                continue;

            var grid = AddCategory(category.ID, GetCategoryName(category), categoryInteractions.Count, ref openFirstCategory);

            foreach (var interaction in categoryInteractions)
                grid.AddChild(PrepareInteractionButton(interaction, category.ID));
        }

        _hasInitializedCategories = true;
        UpdateCatalogSummary(interactions.Count + _availableCustomEmotes.Count);
        UpdateCooldowns(true);
    }

    private GridContainer AddCategory(string id, string name, int count, ref bool openFirst)
    {
        var heading = new CollapsibleHeading(Loc.GetString("rp-panel-category-heading", ("category", name), ("count", count)))
        {
            ChevronMargin = new Thickness(6, 0),
            HorizontalExpand = true,
            MinHeight = 32,
            StyleClasses = { RpPanelStyles.Category },
        };
        heading.Label.StyleClasses.Add(RpPanelStyles.Heading);
        heading.Label.HorizontalExpand = true;
        heading.Label.ClipText = true;

        var category = new Collapsible(heading, new CollapsibleBody())
        {
            HorizontalExpand = true,
        };

        heading.OnToggled += args =>
        {
            if (args.Pressed)
                _openedCategories.Add(id);
            else
                _openedCategories.Remove(id);
        };

        var grid = new GridContainer
        {
            Columns = 2,
            HorizontalExpand = true,
            HSeparationOverride = 6,
            VSeparationOverride = 6,
            Margin = new Thickness(2, 6, 2, 2),
        };

        ButtonsContainer.AddChild(category);
        category.Body?.AddChild(grid);
        _categoryControls[id] = category;

        category.BodyVisible = !string.IsNullOrWhiteSpace(SearchInput.Text) || _openedCategories.Contains(id);
        if (openFirst)
        {
            category.BodyVisible = true;
            _openedCategories.Add(id);
            openFirst = false;
        }

        return grid;
    }

    private Button PrepareInteractionButton(RpInteractionPrototype interaction, string section)
    {
        return CreateInteractionButton(
            $"{section}/{interaction.ID}",
            GetInteractionName(interaction),
            interaction.Kind,
            _sprite.Frame0(interaction.Icon),
            () => OnSendEmote?.Invoke(interaction.ID, PrivateModeToggle.Pressed),
            _favorites.Contains(interaction.ID),
            () => ToggleFavorite(interaction.ID),
            null);
    }

    private Button PrepareCustomEmoteButton(RpCustomEmote emote, string section)
    {
        var icon = _prototypeManager.TryIndex(emote.Category, out var category)
            ? _sprite.Frame0(category.Icon)
            : null;

        return CreateInteractionButton(
            $"{section}/{GetCustomEmoteKey(emote)}",
            emote.Name,
            emote.Kind,
            icon,
            () => OnSendCustomEmote?.Invoke(emote, PrivateModeToggle.Pressed),
            emote.Favorite,
            () => ToggleFavorite(emote),
            section == CustomCategoryId ? () => OpenEditor(emote) : null);
    }

    private Button CreateInteractionButton(
        string key,
        string interactionName,
        RpInteractionKind kind,
        Texture? iconTexture,
        Action send,
        bool favorite,
        Action toggleFavorite,
        Action? edit)
    {
        var harmful = kind == RpInteractionKind.Harmful;

        var button = new Button
        {
            HorizontalExpand = true,
            MinHeight = 52,
            ToolTip = interactionName,
            StyleClasses = { harmful ? DeadSpaceAHelpStyles.ProfileControlDanger : DeadSpaceAHelpStyles.ProfileControl },
        };

        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
            MouseFilter = MouseFilterMode.Ignore,
        };
        content.AddChild(new PanelContainer
        {
            MinWidth = 3,
            VerticalExpand = true,
            StyleClasses = { harmful ? RpPanelStyles.AccentDanger : RpPanelStyles.Accent },
            MouseFilter = MouseFilterMode.Ignore,
        });

        var iconFrame = new PanelContainer
        {
            SetSize = new Vector2(40, 40),
            VerticalAlignment = VAlignment.Center,
            StyleClasses = { RpPanelStyles.IconFrame },
            MouseFilter = MouseFilterMode.Ignore,
        };
        iconFrame.AddChild(new TextureRect
        {
            Texture = iconTexture,
            SetSize = new Vector2(32, 32),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore,
        });
        content.AddChild(iconFrame);

        content.AddChild(new Label
        {
            Text = interactionName,
            StyleClasses = { RpPanelStyles.Text },
            ClipText = true,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore,
        });

        if (edit != null)
        {
            content.AddChild(CreateIconButton(EditIcon, Loc.GetString("rp-panel-custom-edit-tooltip"),
                RpPanelStyles.TextMuted, edit));
        }

        content.AddChild(CreateIconButton(
            StarIcon,
            Loc.GetString(favorite ? "rp-panel-favorite-remove-tooltip" : "rp-panel-favorite-add-tooltip"),
            favorite ? RpPanelStyles.AccentColor : RpPanelStyles.TextPlaceholder.WithAlpha(0.5f),
            toggleFavorite));

        button.AddChild(content);
        button.OnPressed += _ =>
        {
            send();
            _cooldownEnd = _timing.CurTime + RpPanelOwnerComponent.Cooldown;
            UpdateCooldowns(true);
        };

        _interactionButtons[key] = (button, interactionName);
        return button;
    }

    private static Button CreateIconButton(string texturePath, string tooltip, Color modulate, Action onPressed)
    {
        var button = new Button
        {
            SetSize = new Vector2(26, 26),
            VerticalAlignment = VAlignment.Center,
            ToolTip = tooltip,
            StyleClasses = { DeadSpaceAHelpStyles.ProfileControl },
        };
        button.AddChild(new TextureRect
        {
            TexturePath = texturePath,
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            SetSize = new Vector2(14, 14),
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            Modulate = modulate,
            MouseFilter = MouseFilterMode.Ignore,
        });
        button.OnPressed += _ => onPressed();
        return button;
    }

    private string GetCustomEmoteKey(RpCustomEmote emote)
    {
        return $"custom:{_customEmotes.IndexOf(emote)}";
    }

    private void ToggleFavorite(string interactionId)
    {
        if (!_favorites.Remove(interactionId))
            _favorites.Add(interactionId);

        _cfg.SetCVar(LuaMCVars.RpFavoriteInteractions, string.Join(',', _favorites.Order()));
        _cfg.SaveToFile();
        _reloadQueued = true;
    }

    private void ToggleFavorite(RpCustomEmote emote)
    {
        emote.Favorite = !emote.Favorite;
        SaveCustomEmotes();
    }

    private void OpenEditor(RpCustomEmote? emote)
    {
        if (_editor == null)
        {
            _editor = new RpCustomEmoteWindow();
            _editor.OnSave += SaveCustomEmote;
            _editor.OnDelete += DeleteCustomEmote;
            _editor.OnClose += () => _editor = null;
        }

        _editor.SetEmote(emote);
        _editor.OpenCentered();
    }

    private void SaveCustomEmote(RpCustomEmote? original, RpCustomEmote emote)
    {
        var index = original == null ? -1 : _customEmotes.IndexOf(original);
        if (index >= 0)
            _customEmotes[index] = emote;
        else if (_customEmotes.Count < RpCustomEmote.MaxCount)
            _customEmotes.Add(emote);

        SaveCustomEmotes();
    }

    private void DeleteCustomEmote(RpCustomEmote emote)
    {
        _customEmotes.Remove(emote);
        SaveCustomEmotes();
    }

    private void SaveCustomEmotes()
    {
        RpCustomEmoteStorage.Save(_resources, _customEmotes);
        UpdateCreateEmoteButton();
        _reloadQueued = true;
    }

    private void UpdateCreateEmoteButton()
    {
        CreateEmoteButton.Disabled = _customEmotes.Count >= RpCustomEmote.MaxCount;
        CreateEmoteButton.ToolTip = Loc.GetString("rp-panel-custom-create-tooltip",
            ("count", _customEmotes.Count),
            ("max", RpCustomEmote.MaxCount));
    }

    private void UpdateCatalogSummary(int interactionCount)
    {
        ResultsLabel.Text = Loc.GetString("rp-panel-results", ("count", interactionCount));

        var hasInteractions = interactionCount > 0;
        InteractionScroll.Visible = hasInteractions;
        EmptyStateContainer.Visible = !hasInteractions;
        EmptyStateLabel.Text = Loc.GetString(
            !string.IsNullOrWhiteSpace(SearchInput.Text) ? "rp-panel-empty-search"
            : _incapacitated ? "rp-panel-empty-incapacitated"
            : "rp-panel-empty-available");

        ExpandAllButton.Disabled = _categoryControls.Count == 0;
        CollapseAllButton.Disabled = _categoryControls.Count == 0;
    }

    private void SetAllCategoriesExpanded(bool expanded)
    {
        foreach (var (categoryId, category) in _categoryControls)
        {
            category.BodyVisible = expanded;

            if (expanded)
                _openedCategories.Add(categoryId);
            else
                _openedCategories.Remove(categoryId);
        }
    }

    private bool InteractionMatchesSearch(RpInteractionPrototype interaction, string searchText)
    {
        if (string.IsNullOrEmpty(searchText))
            return true;

        if (GetInteractionName(interaction).Contains(searchText, StringComparison.CurrentCultureIgnoreCase))
            return true;

        return _prototypeManager.TryIndex(interaction.Category, out var category)
               && GetCategoryName(category).Contains(searchText, StringComparison.CurrentCultureIgnoreCase);
    }

    private string GetInteractionName(RpInteractionPrototype interaction)
    {
        if (_interactionNames.TryGetValue(interaction.ID, out var name))
            return name;

        name = Loc.GetString($"rp-panel-interaction-{ToKebabCase(interaction.ID)}-name");
        _interactionNames[interaction.ID] = name;
        return name;
    }

    private string GetCategoryName(RpInteractionCategoryPrototype category)
    {
        if (_categoryNames.TryGetValue(category.ID, out var name))
            return name;

        name = GetCategoryLocName(category);
        _categoryNames[category.ID] = name;
        return name;
    }

    internal static string GetCategoryLocName(RpInteractionCategoryPrototype category)
    {
        return Loc.GetString($"rp-panel-category-{ToKebabCase(category.ID)}-name");
    }

    internal static string ToKebabCase(string value)
    {
        var builder = new StringBuilder(value.Length * 2);

        for (var i = 0; i < value.Length; i++)
        {
            var character = value[i];

            if (char.IsUpper(character))
            {
                if (i > 0)
                    builder.Append('-');

                builder.Append(char.ToLowerInvariant(character));
                continue;
            }

            builder.Append(character);
        }

        return builder.ToString();
    }

    private bool CheckRequirements(EntityUid uid, List<RpRequirement>? requirements)
    {
        if (requirements == null)
            return true;

        foreach (var requirement in requirements)
        {
            if (!requirement.IsAvailable(uid, _entManager))
                return false;
        }

        return true;
    }

    private bool IsInRange(EntityUid user, EntityUid target, float range)
    {
        if (_rangeCache.TryGetValue(range, out var inRange))
            return inRange;

        inRange = _interaction.InRangeAndAccessible(user, target, range);
        _rangeCache[range] = inRange;
        return inRange;
    }
}
