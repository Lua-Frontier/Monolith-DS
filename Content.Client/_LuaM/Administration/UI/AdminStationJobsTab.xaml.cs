using System.Linq;
using Content.Client._NF.StationRecords;
using Content.Shared._LuaM.Administration;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._LuaM.Administration.UI;

/// <summary>
/// Admin panel tab with the job slots of the faction stations.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AdminStationJobsTab : Control
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    /// <summary>
    /// How often the slots refresh while the tab is open, players take them all the time.
    /// </summary>
    private static readonly TimeSpan RefreshInterval = TimeSpan.FromSeconds(5);

    private static readonly Color ErrorColor = Color.FromHex("#FF8080");
    private static readonly Color StationColor = Color.FromHex("#A0A0A0");

    private readonly Dictionary<(NetEntity Station, string Job), JobRow> _rows = new();
    private AdminStationJobsSystem? _system;
    private TimeSpan _sinceRefresh;

    public AdminStationJobsTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        StatusLabel.FontColorOverride = ErrorColor;
        RefreshButton.OnPressed += _ => Refresh();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _system = _entMan.System<AdminStationJobsSystem>();
        _system.StateReceived += OnState;
        Refresh();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        if (_system != null)
            _system.StateReceived -= OnState;
        _system = null;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!VisibleInTree)
            return;

        _sinceRefresh += TimeSpan.FromSeconds(args.DeltaSeconds);
        if (_sinceRefresh >= RefreshInterval)
            Refresh();
    }

    private void Refresh()
    {
        _sinceRefresh = TimeSpan.Zero;
        _system?.RequestState();
    }

    private void OnState(AdminStationJobsStateEvent ev)
    {
        StatusLabel.Visible = ev.Error != null;
        StatusLabel.Text = ev.Error ?? string.Empty;
        EmptyLabel.Visible = ev.Entries.Count == 0;

        // rebuilt only when the list changes, so the scroll position survives the refreshes
        if (!_rows.Keys.ToHashSet().SetEquals(ev.Entries.Select(e => (e.Station, e.Job))))
            Rebuild(ev.Entries);

        foreach (var entry in ev.Entries)
        {
            _rows[(entry.Station, entry.Job)].JobAmount.Text = entry.Slots.ToString();
        }
    }

    private void Rebuild(List<AdminStationJobEntry> entries)
    {
        _rows.Clear();
        JobsContainer.RemoveAllChildren();

        foreach (var faction in AdminStationJobFactions.Order)
        {
            var stations = entries
                .Where(e => e.Faction == faction)
                .GroupBy(e => (e.Station, e.StationName))
                .OrderBy(g => g.Key.StationName)
                .ToList();

            if (stations.Count == 0)
                continue;

            var header = new Label
            {
                Text = Loc.GetString($"luam-admin-jobs-faction-{faction}"),
                Margin = new Thickness(0, 8, 0, 2),
            };
            header.AddStyleClass("LabelHeading");
            JobsContainer.AddChild(header);

            foreach (var station in stations)
            {
                JobsContainer.AddChild(new Label
                {
                    Text = station.Key.StationName,
                    FontColorOverride = StationColor,
                });

                foreach (var (entry, name) in station
                             .Select(e => (e, GetJobName(e.Job)))
                             .OrderBy(e => e.Item2))
                {
                    AddRow(entry, name);
                }
            }
        }
    }

    private void AddRow(AdminStationJobEntry entry, string name)
    {
        var row = new JobRow { JobName = { Text = name } };
        row.DecreaseJobSlot.OnPressed += _ => _system?.Change(entry.Station, entry.Job, -1);
        row.IncreaseJobSlot.OnPressed += _ => _system?.Change(entry.Station, entry.Job, 1);

        _rows[(entry.Station, entry.Job)] = row;
        JobsContainer.AddChild(row);
    }

    private string GetJobName(string job)
    {
        return _proto.TryIndex<JobPrototype>(job, out var proto) ? proto.LocalizedName : job;
    }
}
