{
    private const string BagKey = "#bag";
    private const string WeaponKind = "#weapon";
    private const string BagKind = "#bag";
    private const float MiniSize = 40;

    private static readonly string[] LeftSlotOrder = { "head", "eyes", "mask", "balaclava", "ears", "neck", "jumpsuit" };
    private static readonly string[] RightSlotOrder = { "outerClothing", "suitstorage", "gloves", "belt", "back", "shoes", "id" };

    private static readonly Dictionary<string, string> SlotTextures = new()
    {
        { "head", "head" }, { "eyes", "glasses" }, { "mask", "mask" }, { "balaclava", "balaclava" },
        { "ears", "ears" }, { "neck", "neck" }, { "jumpsuit", "uniform" }, { "outerClothing", "suit" },
        { "suitstorage", "suit_storage" }, { "gloves", "gloves" }, { "belt", "belt" }, { "back", "back" },
        { "shoes", "shoes" }, { "id", "id" },
    };

    private static readonly List<LocId> WeaponOrder = new()
    {
        "loadout-group-weapon", "loadout-group-pistol", "loadout-group-special-gun",
        "loadout-group-magazine", "loadout-group-pistol-magazine", "loadout-group-contractor-armorplates",
    };

    private static readonly Dictionary<LocId, LocId> TitleOverrides = new()
    {
        { "loadout-group-pistol", "loadout-editor-slot-secondary" },
        { "loadout-group-special-gun", "loadout-editor-slot-special" },
        { "loadout-group-pistol-magazine", "loadout-editor-slot-pistol-ammo" },
    };

    private static readonly HashSet<string> LockedSlots = new() { "head", "eyes", "ears", "neck", "jumpsuit", "gloves", "belt", "shoes", "id" };

    private static readonly Dictionary<string, string> AttachedTo = new()
    {
        { "ItemCartridge", "id" },
        { "ItemEncryption", "ears" },
    };

    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private MonoCoinsManager _coins = default!;

    private readonly Dictionary<ProtoId<LoadoutGroupPrototype>, (LoadoutGroupContainer? Container, LoadoutSlotButton? Slot)> _groups = new();
    private (HumanoidCharacterProfile Profile, RoleLoadout Loadout, ICommonSession Session, IDependencyCollection Collection)? _context;
    private readonly List<ProtoId<LoadoutGroupPrototype>> _bagGroups = new();
    private readonly HashSet<ProtoId<LoadoutGroupPrototype>> _bagExpanded = new();
    private readonly Dictionary<string, Button> _roleButtons = new();
    private LoadoutSlotButton? _bagSlot;
    private string? _openKey;
    private string? _selectedRole;
    private Direction _direction = Direction.South;
    private RoleLoadout? _loadout;

    public event Action<JobPrototype>? OnRoleSelected;
    public event Action<ProtoId<LoadoutGroupPrototype>, ProtoId<LoadoutPrototype>>? OnLoadoutPressed;
    public event Action<ProtoId<LoadoutGroupPrototype>, ProtoId<LoadoutPrototype>>? OnLoadoutUnpressed;
    public event Action<string>? OnNameChanged;

    public LoadoutEditor()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Rotate(_direction);
        RotateLeft.OnPressed += _ => Rotate(_direction.TurnCw());
        RotateRight.OnPressed += _ => Rotate(_direction.TurnCcw());
        PickerClose.Visible = false;
        RoleNameEdit.PlaceHolder = Loc.GetString("loadout-editor-name-placeholder");
        RoleNameEdit.IsValid = text => text.Length <= HumanoidCharacterProfile.MaxLoadoutNameLength;
        RoleNameEdit.OnTextChanged += args => OnNameChanged?.Invoke(args.Text);
    }

    public void SetPreview(EntityUid entity)
    {
        Preview.SetEntity(entity);
    }

    private void Rotate(Direction direction)
    {
        _direction = direction;
        Preview.OverrideDirection = (Direction) ((int) direction % 4 * 2);
    }

    public void SetRoles(IEnumerable<(string Department, List<JobPrototype> Jobs)> departments)
    {
        RoleList.RemoveAllChildren();
        _roleButtons.Clear();
        var sprites = _entManager.System<SpriteSystem>();

        foreach (var (department, jobs) in departments)
        {
            RoleList.AddChild(new PanelContainer
            {
                PanelOverride = new StyleBoxFlat { BackgroundColor = HudPalette.Border },
                Margin = new Thickness(0, RoleList.ChildCount == 0 ? 0 : 8, 0, 2),
                Children = { new Label { Text = department.ToUpperInvariant(), Margin = new Thickness(6, 2), StyleClasses = { LobbyHudStyles.Mono }, FontColorOverride = HudPalette.Cream } },
            });

            foreach (var job in jobs)
            {
                var icon = new TextureRect
                {
                    TextureScale = new Vector2(2, 2),
                    VerticalAlignment = VAlignment.Center,
                    Margin = new Thickness(0, 0, 5, 0),
                };
                if (_proto.TryIndex(job.Icon, out var jobIcon))
                    icon.Texture = sprites.Frame0(jobIcon.Icon);

                var button = new Button
                {
                    Margin = new Thickness(0, 2),
                };
                button.Label.Visible = false;
                button.AddChild(new BoxContainer
                {
                    Orientation = LayoutOrientation.Horizontal,
                    Margin = new Thickness(6, 2),
                    Children = { icon, new Label { Text = job.LocalizedName, ClipText = true, HorizontalExpand = true } },
                });
                StyleRoleButton(button, job.ID == _selectedRole);
                button.OnPressed += _ => OnRoleSelected?.Invoke(job);

                _roleButtons[job.ID] = button;
                RoleList.AddChild(button);
            }
        }
    }

    private static void StyleRoleButton(Button button, bool active)
    {
        button.ModulateSelfOverride = Color.White;
        button.StyleBoxOverride = HudPalette.Box(
            active ? HudPalette.OrangeDark : HudPalette.Panel,
            active ? HudPalette.Orange : HudPalette.Border,
            active ? HudPalette.Orange : null);

        if (button.ChildCount > 1 && button.GetChild(1) is BoxContainer { ChildCount: 2 } box && box.GetChild(1) is Label label)
            label.FontColorOverride = active ? HudPalette.Orange : HudPalette.Text;
    }

    public void SetRole(JobPrototype job, HumanoidCharacterProfile profile, RoleLoadout loadout, RoleLoadoutPrototype roleProto, ICommonSession session, IDependencyCollection collection)
    {
        _selectedRole = job.ID;
        foreach (var (id, button) in _roleButtons)
        {
            StyleRoleButton(button, id == job.ID);
        }

        RoleTitle.Text = "// " + job.LocalizedName.ToUpperInvariant();
        RoleNameBox.Visible = roleProto.CanCustomizeName;
        if (roleProto.CanCustomizeName)
        {
            LoadoutNameLabel.Text = Loc.GetString(roleProto.NameDataset == null ? "loadout-name-edit-label" : "loadout-name-edit-label-dataset");
            RoleNameEdit.SetText(loadout.EntityName ?? string.Empty, false);
        }

        var reopen = _openKey;
        ClosePicker();
        _groups.Clear();
        _bagGroups.Clear();
        _bagSlot = null;
        LeftSlots.RemoveAllChildren();
        RightSlots.RemoveAllChildren();
        WeaponSlots.RemoveAllChildren();

        var categorizer = new LoadoutCategorizer(_proto, _entManager.System<LoadoutSystem>());
        var kinds = new List<(ProtoId<LoadoutGroupPrototype> Group, LoadoutGroupPrototype Proto, string Kind)>();
        foreach (var group in roleProto.Groups)
        {
            if (!_proto.TryIndex(group, out var groupProto))
                continue;

            var kind = GetGroupKind(groupProto, categorizer);
            if (groupProto.Hidden && !LockedSlots.Contains(kind))
                continue;

            _groups[group] = (null, null);
            kinds.Add((group, groupProto, kind));
        }

        var visible = kinds.Where(k => !k.Proto.Hidden).Select(k => k.Kind).ToHashSet();
        kinds.RemoveAll(k => k.Proto.Hidden && visible.Contains(k.Kind));

        var present = kinds.Select(k => k.Kind).ToHashSet();
        for (var i = 0; i < kinds.Count; i++)
        {
            if (AttachedTo.TryGetValue(kinds[i].Kind, out var parent) && !present.Contains(parent))
                kinds[i] = (kinds[i].Group, kinds[i].Proto, parent);
        }

        var weapons = new List<(int Order, LoadoutSlotButton Slot)>();
        var miniAreas = new Dictionary<string, BoxContainer>();
        PlaceColumn(kinds, LeftSlotOrder, LeftSlots, miniAreas, true);
        PlaceColumn(kinds, RightSlotOrder, RightSlots, miniAreas, false);

        foreach (var (group, groupProto, kind) in kinds)
        {
            if (_groups[group].Slot != null)
                continue;

            if (kind == WeaponKind)
            {
                var slot = CreateSlot(group, GetTitle(groupProto, kind), "hand_r_no_letter", 64);
                slot.Margin = new Thickness(4);
                weapons.Add((WeaponOrder.IndexOf(groupProto.Name) is var i && i >= 0 ? i : WeaponOrder.Count, slot));
                continue;
            }

            if (AttachedTo.TryGetValue(kind, out var parentSlot) && miniAreas.TryGetValue(parentSlot, out var area))
            {
                var mini = CreateSlot(group, null, "pocket", MiniSize);
                area.AddChild(mini);
                continue;
            }

            _bagGroups.Add(group);
        }

        foreach (var (_, slot) in weapons.OrderBy(w => w.Order))
        {
            WeaponSlots.AddChild(slot);
        }

        if (_bagGroups.Count > 0)
        {
            _bagSlot = new LoadoutSlotButton(Loc.GetString("loadout-editor-bag"), "pocket");
            _bagSlot.Button.OnPressed += _ => OpenPicker(BagKey);
            RightSlots.AddChild(CreateRow(_bagSlot, false, out _));
        }

        RefreshSlots(profile, loadout, session, collection);

        if (reopen != null && (reopen == BagKey ? _bagSlot != null : _groups.ContainsKey(reopen)))
            OpenPicker(reopen);
        else if (_bagSlot != null)
            OpenPicker(BagKey);
        else if (_groups.FirstOrDefault(g => g.Value.Slot != null).Key is var first && first != default)
            OpenPicker(first);
    }

    private void PlaceColumn(List<(ProtoId<LoadoutGroupPrototype> Group, LoadoutGroupPrototype Proto, string Kind)> kinds,
        string[] order, BoxContainer column, Dictionary<string, BoxContainer> miniAreas, bool left)
    {
        foreach (var slotName in order)
        {
            foreach (var (group, groupProto, kind) in kinds)
            {
                if (kind != slotName || _groups[group].Slot != null)
                    continue;

                var slot = CreateSlot(group, GetTitle(groupProto, slotName), SlotTextures[slotName], 64);
                slot.SetLocked(groupProto.Hidden);
                column.AddChild(CreateRow(slot, left, out var area));
                miniAreas.TryAdd(slotName, area);
            }
        }
    }

    private static BoxContainer CreateRow(LoadoutSlotButton slot, bool left, out BoxContainer miniArea)
    {
        miniArea = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            SetWidth = MiniSize + 8,
            VerticalAlignment = VAlignment.Center,
        };

        var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal };
        if (left)
        {
            row.AddChild(miniArea);
            row.AddChild(slot);
        }
        else
        {
            row.AddChild(slot);
            row.AddChild(miniArea);
        }

        return row;
    }

    private static string GetTitle(LoadoutGroupPrototype group, string kind)
    {
        if (kind == "back")
            return Loc.GetString("loadout-editor-slot-back");

        return Loc.GetString(TitleOverrides.TryGetValue(group.Name, out var title) ? title : group.Name);
    }

    private LoadoutSlotButton CreateSlot(ProtoId<LoadoutGroupPrototype> group, string? title, string texture, float size)
    {
        var slot = new LoadoutSlotButton(title, texture, size);
        slot.Button.OnPressed += _ => OpenPicker(group);

        if (title == null && _proto.TryIndex(group, out var groupProto))
            slot.ToolTip = Loc.GetString(groupProto.Name);

        _groups[group] = (_groups[group].Container, slot);
        return slot;
    }

    private string GetGroupKind(LoadoutGroupPrototype group, LoadoutCategorizer categorizer)
    {
        var loadouts = group.Loadouts.Concat(group.Subgroups
                .SelectMany(s => _proto.TryIndex(s, out var sub) ? sub.Loadouts : new List<ProtoId<LoadoutPrototype>>()))
            .Select(id => _proto.TryIndex(id, out var loadout) ? loadout : null)
            .OfType<LoadoutPrototype>()
            .ToList();

        if (loadouts.Count == 0)
            return BagKind;

        var slot = loadouts
            .Select(l => LoadoutCategorizer.GetSlot(l, _proto))
            .GroupBy(s => s)
            .OrderByDescending(g => g.Count())
            .First().Key;

        if (slot != LoadoutCategorizer.StorageSlot)
            return SlotTextures.ContainsKey(slot) ? slot : BagKind;

        var category = loadouts
            .Select(l => categorizer.Categorize(l)?.ID ?? LoadoutCategorizer.OtherCategory)
            .GroupBy(id => id)
            .OrderByDescending(g => g.Count())
            .First().Key;

        if (category.StartsWith("Weapon") || category.StartsWith("Ammo") || category is "ItemArmorPlate" or "ItemMelee")
            return WeaponKind;

        if (category == "ItemMask")
            return "mask";

        return AttachedTo.ContainsKey(category) ? category : BagKind;
    }

    public void RefreshSlots(HumanoidCharacterProfile profile, RoleLoadout loadout, ICommonSession session, IDependencyCollection collection)
    {
        _loadout = loadout;
        var bagNames = new List<string>();

        _context = (profile, loadout, session, collection);
        foreach (var (group, (container, slot)) in _groups)
        {
            container?.RefreshLoadouts(profile, loadout, session, collection);
            var (icon, names) = GetSelected(group, loadout);

            if (slot != null)
            {
                var title = _proto.TryIndex(group, out var groupProto) ? Loc.GetString(groupProto.Name) : group.Id;
                if (groupProto?.Hidden == true)
                    title = Loc.GetString("loadout-editor-slot-locked", ("name", title));

                slot.SetItem(icon, names.Count > 0 ? $"{title}:\n{string.Join("\n", names)}" : $"{title}: {Loc.GetString("loadout-editor-slot-empty")}");
            }
            else if (_bagGroups.Contains(group))
            {
                bagNames.AddRange(names);
            }
        }

        _bagSlot?.SetItem(null, bagNames.Count > 0 ? string.Join("\n", bagNames) : Loc.GetString("loadout-editor-slot-empty"));

        if (_openKey == BagKey)
            BuildBagPicker();

        UpdateCost(loadout);
        Balance.Text = Loc.GetString("frontier-loadout-balance",
            ("balance", BankSystemExtensions.ToSpesoString(profile.BankBalance)),
            ("savings", BankSystemExtensions.ToSpesoString(_coins.GetLastKnownBalance())));
    }

    private (EntProtoId? Icon, List<string> Names) GetSelected(ProtoId<LoadoutGroupPrototype> group, RoleLoadout loadout)
    {
        var loadoutSystem = _entManager.System<LoadoutSystem>();
        EntProtoId? icon = null;
        var names = new List<string>();

        if (!loadout.SelectedLoadouts.TryGetValue(group, out var selected))
            return (icon, names);

        foreach (var item in selected)
        {
            if (!_proto.TryIndex(item.Prototype, out var itemProto))
                continue;

            icon ??= itemProto.PreviewEntity ?? loadoutSystem.GetFirstOrNull(itemProto);
            names.Add(string.IsNullOrEmpty(itemProto.Name) ? loadoutSystem.GetName(itemProto) : itemProto.Name);
        }

        return (icon, names);
    }

    private LoadoutGroupContainer? GetContainer(ProtoId<LoadoutGroupPrototype> group)
    {
        if (!_groups.TryGetValue(group, out var entry))
            return null;

        if (entry.Container != null)
            return entry.Container;

        if (_context is not { } ctx || !_proto.TryIndex(group, out var groupProto))
            return null;

        var container = new LoadoutGroupContainer(ctx.Profile, ctx.Loadout, groupProto, ctx.Session, ctx.Collection);
        container.OnLoadoutPressed += args => OnLoadoutPressed?.Invoke(group, args);
        container.OnLoadoutUnpressed += args => OnLoadoutUnpressed?.Invoke(group, args);
        _groups[group] = (container, entry.Slot);
        return container;
    }

    private void UpdateCost(RoleLoadout loadout)
    {
        var cost = 0;
        foreach (var group in loadout.SelectedLoadouts.Values)
        {
            foreach (var item in group)
            {
                if (_proto.TryIndex(item.Prototype, out var itemProto))
                    cost += itemProto.Price;
            }
        }

        Cost.Text = Loc.GetString("frontier-loadout-cost", ("cost", BankSystemExtensions.ToSpesoString(cost)));
    }

    private void OpenPicker(string key)
    {
        ClosePicker();
        _openKey = key;

        if (key == BagKey)
        {
            _bagSlot?.SetPressed(true);
            PickerTitle.Text = Loc.GetString("loadout-editor-bag").ToUpperInvariant();
            BuildBagPicker();
        }
        else
        {
            if (!_groups.TryGetValue(key, out var entry))
                return;

            entry.Slot?.SetPressed(true);
            PickerTitle.Text = _proto.TryIndex<LoadoutGroupPrototype>(key, out var groupProto) ? Loc.GetString(groupProto.Name).ToUpperInvariant() : key.ToUpperInvariant();
            var groupContainer = GetContainer(key);
            if (groupContainer == null)
                return;

            groupContainer.Orphan();
            PickerContent.AddChild(groupContainer);
        }

        PickerPanel.Visible = true;
    }

    private void BuildBagPicker()
    {
        PickerContent.RemoveAllChildren();

        foreach (var group in _bagGroups)
        {
            var container = GetContainer(group);
            if (container == null)
                continue;

            var (icon, names) = _loadout != null ? GetSelected(group, _loadout) : (null, new List<string>());
            var name = _proto.TryIndex(group, out var groupProto) ? Loc.GetString(groupProto.Name) : group.Id;
            var title = names.Count > 0
                ? Loc.GetString("loadout-category-title-selected", ("name", name), ("count", names.Count))
                : name;

            var expanded = _bagExpanded.Contains(group);
            var body = new BoxContainer { Orientation = LayoutOrientation.Vertical, Margin = new Thickness(15, 0, 0, 0), Visible = expanded };
            container.Orphan();
            if (expanded)
                body.AddChild(container);

            var header = new LoadoutCategoryHeader(title, icon ?? GetFirstIcon(groupProto), expanded);
            header.OnToggled += pressed =>
            {
                if (pressed && body.ChildCount == 0)
                    body.AddChild(container);

                body.Visible = pressed;
                if (pressed)
                    _bagExpanded.Add(group);
                else
                    _bagExpanded.Remove(group);
            };

            PickerContent.AddChild(header);
            PickerContent.AddChild(body);
        }
    }

    private EntProtoId? GetFirstIcon(LoadoutGroupPrototype? group)
    {
        if (group == null)
            return null;

        var loadoutSystem = _entManager.System<LoadoutSystem>();
        foreach (var id in group.Loadouts)
        {
            if (_proto.TryIndex(id, out var loadout) && (loadout.PreviewEntity ?? loadoutSystem.GetFirstOrNull(loadout)) is { } icon)
                return icon;
        }

        return null;
    }

    private void ClosePicker()
    {
        if (_openKey == BagKey)
            _bagSlot?.SetPressed(false);
        else if (_openKey != null && _groups.TryGetValue(_openKey, out var entry))
            entry.Slot?.SetPressed(false);

        _openKey = null;
        PickerContent.RemoveAllChildren();
        PickerPanel.Visible = false;
    }
}
