using Content.Client._LuaM.UserInterface.Hud;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map;
using Robust.Shared.Prototypes;

namespace Content.Client._LuaM.Lobby;

[GenerateTypedNameReferences]
public sealed partial class LoadoutCategoryHeader : BoxContainer
{
    private static readonly Color NameColor = HudPalette.Panel;
    private static readonly Color NameColorHovered = HudPalette.PanelHover;

    [Dependency] private IEntityManager _entManager = default!;

    private readonly EntProtoId? _iconProto;
    private readonly StyleBoxFlat _nameStyle = new() { BorderThickness = new Thickness(1) };
    private EntityUid? _entity;
    private bool _hovered;

    public event Action<bool>? OnToggled;

    public LoadoutCategoryHeader(string title, EntProtoId? icon, bool expanded)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _iconProto = icon;
        ArrowButton.Label.Visible = false;
        NameButton.Label.Visible = false;
        NameButton.StyleBoxOverride = _nameStyle;
        NameLabel.Text = title;

        NameButton.OnMouseEntered += _ => SetHovered(true);
        NameButton.OnMouseExited += _ => SetHovered(false);
        ArrowButton.OnToggled += args => SetExpanded(args.Pressed);
        NameButton.OnToggled += args => SetExpanded(args.Pressed);
        SetExpanded(expanded, false);
    }

    private void SetHovered(bool hovered)
    {
        _hovered = hovered;
        NameLabel.Hovered = hovered;
        UpdateColor();
    }

    private void SetExpanded(bool expanded, bool notify = true)
    {
        ArrowButton.Pressed = expanded;
        NameButton.Pressed = expanded;
        ArrowLabel.Text = expanded ? "▼" : "►";
        UpdateColor();

        if (notify)
            OnToggled?.Invoke(expanded);
    }

    private void UpdateColor()
    {
        var open = NameButton.Pressed;
        _nameStyle.BackgroundColor = open ? HudPalette.OrangeDark : _hovered ? NameColorHovered : NameColor;
        _nameStyle.BorderColor = open ? HudPalette.Orange : _hovered ? HudPalette.BorderBright : HudPalette.Border;
        NameLabel.FontColorOverride = open ? HudPalette.Orange : null;
        ArrowLabel.FontColorOverride = open ? HudPalette.Orange : HudPalette.Cyan;
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        if (_iconProto == null || _entity != null)
            return;

        _entity = _entManager.SpawnEntity(_iconProto, MapCoordinates.Nullspace);
        Sprite.SetEntity(_entity);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        Sprite.SetEntity(null);
        _entManager.DeleteEntity(_entity);
        _entity = null;
    }
}
