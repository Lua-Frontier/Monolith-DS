using System.Numerics;
using Content.Client.SprayPainter;
using Content.Client.Stylesheets;
using Content.Shared.Decals;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._LuaM.SprayPainter;

/// <summary>
/// Decal painting settings tab of the spray painter window.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SprayPainterDecalsControl : Control
{
    public Action<ProtoId<DecalPrototype>>? OnDecalSelected;
    public Action<Color?>? OnColorChanged;
    public Action<int>? OnAngleChanged;
    public Action<bool>? OnSnapChanged;

    private SpriteSystem? _sprite;
    private string _selectedDecal = string.Empty;
    private List<SprayPainterDecalEntry> _decals = new();

    public SprayPainterDecalsControl()
    {
        RobustXamlLoader.Load(this);

        AddAngleButton.OnButtonUp += _ => AngleSpinBox.Value += 90;
        SubAngleButton.OnButtonUp += _ => AngleSpinBox.Value -= 90;
        SetZeroAngleButton.OnButtonUp += _ => AngleSpinBox.Value = 0;
        AngleSpinBox.ValueChanged += args => OnAngleChanged?.Invoke(args.Value);

        UseCustomColorCheckBox.OnPressed += _ =>
        {
            OnColorChanged?.Invoke(UseCustomColorCheckBox.Pressed ? ColorSelector.Color : null);
            UpdateColorButtons();
        };
        SnapToTileCheckBox.OnPressed += _ => OnSnapChanged?.Invoke(SnapToTileCheckBox.Pressed);
        ColorSelector.OnColorChanged += OnColorSelected;
        Search.OnTextChanged += _ => RefreshGrid();
    }

    public void PopulateDecals(List<SprayPainterDecalEntry> decals, SpriteSystem sprite)
    {
        _sprite = sprite;
        _decals = decals;
        RefreshGrid();
    }

    private static string DecalName(string id)
    {
        return IoCManager.Resolve<ILocalizationManager>().TryGetString($"decal-name-{id}", out var name) ? name : id;
    }

    private void RefreshGrid()
    {
        DecalsGrid.RemoveAllChildren();
        if (_sprite == null)
            return;

        var filter = Search.Text.Trim().ToLowerInvariant();
        var modulate = UseCustomColorCheckBox.Pressed ? ColorSelector.Color : Color.White;
        foreach (var decal in _decals)
        {
            var name = DecalName(decal.Name);
            if (filter.Length > 0
                && !decal.Name.ToLowerInvariant().Contains(filter)
                && !name.ToLowerInvariant().Contains(filter))
                continue;

            var button = new TextureButton
            {
                TextureNormal = _sprite.Frame0(decal.Sprite),
                Name = decal.Name,
                ToolTip = name,
                Scale = new Vector2(2, 2),
                Modulate = modulate,
            };
            button.OnPressed += DecalButtonOnPressed;

            if (_selectedDecal == decal.Name)
            {
                DecalsGrid.AddChild(new PanelContainer
                {
                    PanelOverride = new StyleBoxFlat { BackgroundColor = StyleNano.ButtonColorDefault },
                    Children = { button },
                });
            }
            else
            {
                DecalsGrid.AddChild(button);
            }
        }
    }

    private void OnColorSelected(Color color)
    {
        if (!UseCustomColorCheckBox.Pressed)
            return;

        OnColorChanged?.Invoke(color);
        UpdateColorButtons();
    }

    private void UpdateColorButtons()
    {
        var modulate = UseCustomColorCheckBox.Pressed ? ColorSelector.Color : Color.White;
        foreach (var child in DecalsGrid.Children)
        {
            switch (child)
            {
                case TextureButton:
                    child.Modulate = modulate;
                    break;
                case PanelContainer panel:
                    foreach (var inner in panel.Children)
                        inner.Modulate = modulate;
                    break;
            }
        }
    }

    private void DecalButtonOnPressed(BaseButton.ButtonEventArgs obj)
    {
        if (obj.Button.Name is not { } name)
            return;

        _selectedDecal = name;
        OnDecalSelected?.Invoke(name);
        RefreshGrid();
    }

    public void SetSelectedDecal(string name)
    {
        if (_selectedDecal == name)
            return;

        _selectedDecal = name;
        RefreshGrid();
    }

    public void SetAngle(int degrees)
    {
        AngleSpinBox.OverrideValue(degrees);
    }

    public void SetColor(Color? color)
    {
        UseCustomColorCheckBox.Pressed = color != null;
        if (color != null)
            ColorSelector.Color = color.Value;
        UpdateColorButtons();
    }

    public void SetSnap(bool snap)
    {
        SnapToTileCheckBox.Pressed = snap;
    }
}
