using System.Linq;
using System.Numerics;
using Content.Client._LuaM.UserInterface.Hud;
using Content.Client.Message;
using Content.Client.Stylesheets;
using Content.Shared._LuaM.Roadmap;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._LuaM.Roadmap;

/// <summary>
/// The roadmap in the lobby HUD look: a chamfered window with three columns of plans.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class RoadmapWindow : BaseWindow
{
    [Dependency] private IPrototypeManager _proto = default!;

    private const float ResizeMargin = 6;

    private static readonly (RoadmapStage Stage, LocId Title, HudStatus Status)[] Stages =
    {
        (RoadmapStage.Near, "roadmap-column-near", HudStatus.Caution),
        (RoadmapStage.Later, "roadmap-column-later", HudStatus.Advisory),
        (RoadmapStage.Done, "roadmap-column-done", HudStatus.Nominal),
    };

    public RoadmapWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Header.Title = Loc.GetString("roadmap-window-title");
        CloseButton.OnPressed += _ => Close();
    }

    protected override void Opened()
    {
        base.Opened();
        Populate();
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        var mode = DragMode.None;

        if (relativeMousePos.Y < ResizeMargin)
            mode = DragMode.Top;
        else if (relativeMousePos.Y > Size.Y - ResizeMargin)
            mode = DragMode.Bottom;

        if (relativeMousePos.X < ResizeMargin)
            mode |= DragMode.Left;
        else if (relativeMousePos.X > Size.X - ResizeMargin)
            mode |= DragMode.Right;

        if (mode == DragMode.None && relativeMousePos.Y < StyleBoxHud.WindowHeader)
            mode = DragMode.Move;

        return mode;
    }

    private void Populate()
    {
        Columns.RemoveAllChildren();

        foreach (var (stage, title, status) in Stages)
        {
            var items = _proto.EnumeratePrototypes<RoadmapItemPrototype>()
                .Where(p => p.Stage == stage)
                .OrderBy(p => p.Order)
                .ThenBy(p => p.ID)
                .ToList();

            Columns.AddChild(MakeColumn(title, status, items));
        }
    }

    private static Control MakeColumn(LocId title, HudStatus status, List<RoadmapItemPrototype> items)
    {
        var color = HudStatusColors.Of(status);

        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
        };
        header.AddChild(new HudShape { Status = status, SetSize = new Vector2(9, 9) });
        header.AddChild(new Label
        {
            Text = Loc.GetString(title).ToUpperInvariant(),
            StyleClasses = { LobbyHudStyles.Heading },
            FontColorOverride = color,
            VAlign = Label.VAlignMode.Center,
        });
        header.AddChild(new PanelContainer
        {
            HorizontalExpand = true,
            MinHeight = 1,
            VerticalAlignment = VAlignment.Center,
            PanelOverride = new StyleBoxFlat { BackgroundColor = HudPalette.LineDim },
        });
        header.AddChild(new Label
        {
            Text = items.Count.ToString("00"),
            StyleClasses = { LobbyHudStyles.Mark },
            VAlign = Label.VAlignMode.Center,
        });

        var list = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 6,
            Margin = new Thickness(0, 0, 6, 0),
        };

        if (items.Count == 0)
        {
            list.AddChild(new Label
            {
                Text = Loc.GetString("roadmap-column-empty").ToUpperInvariant(),
                StyleClasses = { LobbyHudStyles.MonoDim },
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 16, 0, 0),
            });
        }

        for (var i = 0; i < items.Count; i++)
        {
            list.AddChild(MakeCard(items[i], color, i + 1));
        }

        var scroll = new ScrollContainer { HScrollEnabled = false, VerticalExpand = true };
        scroll.AddChild(list);

        var field = new PanelContainer
        {
            VerticalExpand = true,
            PanelOverride = new StyleBoxGrid
            {
                Step = 0,
                ContentMarginLeftOverride = 8,
                ContentMarginRightOverride = 4,
                ContentMarginTopOverride = 8,
                ContentMarginBottomOverride = 8,
            },
        };
        field.AddChild(scroll);

        var column = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 8,
            HorizontalExpand = true,
            VerticalExpand = true,
        };
        column.AddChild(header);
        column.AddChild(field);
        return column;
    }

    private static Control MakeCard(RoadmapItemPrototype item, Color color, int index)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 3,
        };

        var top = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
        };
        top.AddChild(new Label
        {
            Text = index.ToString("00"),
            StyleClasses = { LobbyHudStyles.Mark },
            FontColorOverride = color,
            VAlign = Label.VAlignMode.Top,
            Margin = new Thickness(0, 3, 0, 0),
        });

        // RichTextLabel wraps long names onto the next line, a Label would cut them off.
        var name = new RichTextLabel { StyleClasses = { LobbyHudStyles.Body }, HorizontalExpand = true };
        name.SetMarkupPermissive($"[color={HudPalette.Text.ToHex()}]{FormattedMessage.EscapeText(Loc.GetString(item.Name))}[/color]");
        top.AddChild(name);
        box.AddChild(top);

        if (item.Description is { } description)
        {
            var desc = new RichTextLabel { StyleClasses = { LobbyHudStyles.Body }, Margin = new Thickness(24, 0, 0, 0) };
            desc.SetMarkupPermissive($"[color={HudPalette.TextDim.ToHex()}]{Loc.GetString(description)}[/color]");
            box.AddChild(desc);
        }

        var style = new StyleBoxHud(HudPalette.PanelRaised, HudPalette.LineDim, color)
        {
            Chamfer = 6,
            AccentWidth = 2,
        };
        style.SetContentMarginOverride(StyleBox.Margin.Left, 12);
        style.SetContentMarginOverride(StyleBox.Margin.Right, 8);
        style.SetContentMarginOverride(StyleBox.Margin.Vertical, 7);

        var card = new PanelContainer { PanelOverride = style };
        card.AddChild(box);
        return card;
    }
}
