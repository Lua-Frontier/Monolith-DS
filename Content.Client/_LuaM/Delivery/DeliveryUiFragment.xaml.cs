[GenerateTypedNameReferences]
public sealed partial class DeliveryUiFragment : BoxContainer
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private const int SummaryItems = 6;
    private const int PageSize = 25;
    private const int AllCategory = 0;
    private const int CartCategory = 1;
    private const int FirstSectionCategory = 2;

    private static readonly Color HintColor = Color.FromHex("#A0A0A0");
    private static readonly Color CardColor = Color.FromHex("#25231C");
    private static readonly Color RowColor = Color.FromHex("#1B1A16");
    private static readonly Color RowAltColor = Color.FromHex("#23211B");
    private static readonly Color AccentColor = Color.FromHex("#F2C21B");
    private static readonly Color AppBackgroundColor = Color.FromHex("#141310");
    private static readonly Color InkColor = Color.FromHex("#141414");
    private static readonly Color TabColor = Color.FromHex("#2B2820");
    private static readonly Color DisabledColor = Color.FromHex("#3A372E");

    // -- Каталог кешируется на весь клиент: сервер шлёт его только по запросу при смене хеша
    private static int _cachedHash;
    private static List<string> _cachedSections = new();
    private static List<CatalogItem> _cachedItems = new();

    public event Action<Dictionary<string, int>>? OnOrder;
    public event Action<int>? OnTake;
    public event Action? OnRequestCatalog;

    private readonly Dictionary<string, int> _cart = new();
    private readonly Dictionary<string, int> _prices = new();
    private readonly Dictionary<string, CatalogRow> _rows = new();
    private readonly List<(Label Label, TimeSpan ExpiresAt)> _timers = new();
    private readonly Dictionary<int, Label> _positionLabels = new();

    private int _builtHash;
    private int _requestedHash;
    private int _category = AllCategory;
    private int _page;
    private int _balance;
    private int _myOrders;
    private int? _clearCartAbove;
    private int _shownSecond = -1;
    private DeliveryUiMode? _lastMode;
    private string? _courierSignature;

    public DeliveryUiFragment()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        AppBackground.PanelOverride = new StyleBoxFlat { BackgroundColor = AppBackgroundColor };
        var header = new StyleBoxFlat { BackgroundColor = AccentColor };
        ShopHeader.PanelOverride = header;
        CourierHeader.PanelOverride = header;
        ShopTitleLabel.FontColorOverride = InkColor;
        ShopBalanceLabel.FontColorOverride = InkColor;
        CourierProfileLabel.FontColorOverride = InkColor;
        CourierNameLabel.FontColorOverride = InkColor;

        CatalogTabButton.OnPressed += _ => SetOrdersTab(false);
        OrdersTabButton.OnPressed += _ => SetOrdersTab(true);
        SetOrdersTab(false);

        SearchInput.OnTextChanged += _ =>
        {
            _page = 0;
            RebuildPage();
        };
        CategorySelect.OnItemSelected += args =>
        {
            CategorySelect.SelectId(args.Id);
            _category = args.Id;
            _page = 0;
            RebuildPage();
        };
        PrevPageButton.OnPressed += _ =>
        {
            _page--;
            RebuildPage();
        };
        NextPageButton.OnPressed += _ =>
        {
            _page++;
            RebuildPage();
        };
        ClearButton.OnPressed += _ =>
        {
            _cart.Clear();
            RefreshCart();
            if (_category == CartCategory)
                RebuildPage();
        };
        OrderButton.OnPressed += args =>
        {
            if (!CanOrder(out _, out _))
                return;

            _clearCartAbove = _myOrders;
            OnOrder?.Invoke(new Dictionary<string, int>(_cart));
        };
    }

    public void UpdateState(DeliveryUiState state)
    {
        if (state.Mode != _lastMode)
        {
            _lastMode = state.Mode;
            _timers.Clear();
            _courierSignature = null;
        }

        _shownSecond = -1;
        _balance = state.Balance ?? 0;

        BannerBox.Visible = state.Mode is DeliveryUiMode.Maintenance or DeliveryUiMode.AccountUnavailable;
        ShopBox.Visible = state.Mode == DeliveryUiMode.Shop;
        CourierBox.Visible = state.Mode == DeliveryUiMode.Courier;
        AppBackground.Visible = ShopBox.Visible || CourierBox.Visible;

        switch (state.Mode)
        {
            case DeliveryUiMode.Maintenance:
                BannerBox.SetWarning(Loc.GetString("delivery-ui-maintenance"), Loc.GetString("delivery-ui-maintenance-hint"));
                break;
            case DeliveryUiMode.AccountUnavailable:
                BannerBox.SetAlert(Loc.GetString("delivery-ui-account-unavailable"), Loc.GetString("delivery-ui-account-unavailable-hint"));
                break;
            case DeliveryUiMode.Shop:
                UpdateShop(state);
                break;
            case DeliveryUiMode.Courier:
                UpdateCourier(state);
                break;
        }

        UpdateTimers();
    }

    #region Shop

    private void SetOrdersTab(bool orders)
    {
        CatalogPanel.Visible = !orders;
        OrdersPanel.Visible = orders;
        CatalogTabButton.Pressed = !orders;
        OrdersTabButton.Pressed = orders;
        PaintButton(CatalogTabButton, !orders);
        PaintButton(OrdersTabButton, orders);
    }

    private static void PaintButton(Button button, bool accent)
    {
        var color = button.Disabled ? DisabledColor : accent ? AccentColor : TabColor;
        button.StyleBoxOverride = new StyleBoxFlat
        {
            BackgroundColor = color,
            ContentMarginLeftOverride = 6,
            ContentMarginRightOverride = 6,
            ContentMarginTopOverride = 2,
            ContentMarginBottomOverride = 2,
        };
        // -- Стиль кнопок перекрашивает их через modulate по состоянию: без белого оверрайда жёлтый становится зелёным
        button.ModulateSelfOverride = Color.White;
        button.Label.FontColorOverride = accent && !button.Disabled ? InkColor : null;
    }

    private void UpdateShop(DeliveryUiState state)
    {
        ShopBalanceLabel.Text = Loc.GetString("delivery-ui-balance", ("amount", YupiRules.FormatCredits(_balance)));

        if (state.Catalog != null)
            CacheCatalog(state.CatalogHash, state.Catalog);
        else if (state.CatalogHash != _cachedHash && state.CatalogHash != _requestedHash)
        {
            _requestedHash = state.CatalogHash;
            OnRequestCatalog?.Invoke();
        }

        var loaded = state.CatalogHash == _cachedHash;
        CatalogStatusLabel.Visible = !loaded;
        CatalogStatusLabel.Text = Loc.GetString("delivery-ui-catalog-loading");
        if (loaded && _builtHash != _cachedHash)
            BuildCategories();

        if (_clearCartAbove is { } before && state.Orders.Count > before)
        {
            _cart.Clear();
            _clearCartAbove = null;
            if (_category == CartCategory)
                RebuildPage();

            SetOrdersTab(true);
        }

        _myOrders = state.Orders.Count;
        OrdersTabButton.Text = Loc.GetString("delivery-ui-tab-orders", ("count", _myOrders));
        _timers.Clear();
        MyOrdersList.RemoveAllChildren();
        NoMyOrdersLabel.Visible = state.Orders.Count == 0;
        foreach (var order in state.Orders)
        {
            MyOrdersList.AddChild(BuildOrderCard(order, false));
        }

        RefreshCart();
    }

    private void CacheCatalog(int hash, List<DeliveryCatalogSection> catalog)
    {
        var sections = new List<string>();
        var items = new List<CatalogItem>();
        foreach (var section in catalog)
        {
            var index = sections.Count;
            sections.Add(section.Name);
            foreach (var entry in section.Entries)
            {
                if (!_proto.TryIndex<EntityPrototype>(entry.Prototype, out var proto))
                    continue;

                items.Add(new CatalogItem(entry.Prototype, proto.Name, entry.Price, index));
            }
        }

        items.Sort((a, b) => string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase));

        _cachedHash = hash;
        _cachedSections = sections;
        _cachedItems = items;
    }

    private void BuildCategories()
    {
        _builtHash = _cachedHash;
        _prices.Clear();
        foreach (var item in _cachedItems)
            _prices[item.Prototype] = item.Price;

        foreach (var proto in _cart.Keys.ToList())
        {
            if (!_prices.ContainsKey(proto))
                _cart.Remove(proto);
        }

        CategorySelect.Clear();
        CategorySelect.AddItem(Loc.GetString("delivery-category-all"), AllCategory);
        CategorySelect.AddItem(Loc.GetString("delivery-category-cart"), CartCategory);
        for (var i = 0; i < _cachedSections.Count; i++)
        {
            var name = _cachedSections[i];
            CategorySelect.AddItem(Loc.TryGetString(name, out var localized) ? localized : name, FirstSectionCategory + i);
        }

        if (_category >= FirstSectionCategory + _cachedSections.Count)
            _category = AllCategory;

        CategorySelect.SelectId(_category);
        _page = 0;
        RebuildPage();
    }

    private void RebuildPage()
    {
        _rows.Clear();
        CatalogList.RemoveAllChildren();

        if (_builtHash == 0)
        {
            PageLabel.Text = string.Empty;
            PrevPageButton.Disabled = true;
            NextPageButton.Disabled = true;
            return;
        }

        var filter = SearchInput.Text.Trim();
        var matches = new List<CatalogItem>();
        foreach (var item in _cachedItems)
        {
            if (_category == CartCategory && !_cart.ContainsKey(item.Prototype))
                continue;

            if (_category >= FirstSectionCategory && item.Section != _category - FirstSectionCategory)
                continue;

            if (filter.Length > 0 && !item.Name.Contains(filter, StringComparison.CurrentCultureIgnoreCase))
                continue;

            matches.Add(item);
        }

        var pages = Math.Max(1, (matches.Count + PageSize - 1) / PageSize);
        _page = Math.Clamp(_page, 0, pages - 1);

        PageLabel.Text = Loc.GetString("delivery-ui-page", ("page", _page + 1), ("pages", pages), ("count", matches.Count));
        PrevPageButton.Disabled = _page == 0;
        NextPageButton.Disabled = _page >= pages - 1;

        var start = _page * PageSize;
        var end = Math.Min(start + PageSize, matches.Count);
        for (var i = start; i < end; i++)
        {
            var item = matches[i];
            var row = new CatalogRow(item, (i - start) % 2 == 0 ? RowColor : RowAltColor);
            row.Minus.OnPressed += _ => ChangeCart(item.Prototype, -1);
            row.Plus.OnPressed += _ => ChangeCart(item.Prototype, 1);
            _rows[item.Prototype] = row;
            CatalogList.AddChild(row.Root);
        }

        if (matches.Count == 0)
        {
            CatalogList.AddChild(new Label
            {
                Text = Loc.GetString(_category == CartCategory ? "delivery-ui-cart-empty" : "delivery-ui-nothing-found"),
                FontColorOverride = HintColor,
                Margin = new Thickness(4),
            });
        }

        CatalogScroll.SetScrollValue(Vector2.Zero);
        RefreshCart();
    }

    private void ChangeCart(string proto, int delta)
    {
        _cart.TryGetValue(proto, out var current);
        var count = Math.Clamp(current + delta, 0, DeliveryRules.MaxItems);
        if (delta > 0 && GetCartCount() >= DeliveryRules.MaxItems)
            count = current;

        if (count == 0)
            _cart.Remove(proto);
        else
            _cart[proto] = count;

        RefreshCart();
    }

    private int GetCartCount()
    {
        return _cart.Values.Sum();
    }

    private long GetCartTotal()
    {
        long total = 0;
        foreach (var (proto, count) in _cart)
        {
            if (_prices.TryGetValue(proto, out var price))
                total += (long) price * count;
        }

        return total;
    }

    private bool CanOrder(out int count, out long total)
    {
        count = GetCartCount();
        total = GetCartTotal();
        return count > 0
            && count <= DeliveryRules.MaxItems
            && total >= DeliveryRules.MinOrderTotal
            && total <= _balance;
    }

    private void RefreshCart()
    {
        foreach (var (proto, row) in _rows)
        {
            _cart.TryGetValue(proto, out var count);
            row.Count.Text = count.ToString();
            row.Minus.Disabled = count == 0;
        }

        var canOrder = CanOrder(out var itemCount, out var total);
        OrderButton.Disabled = !canOrder;
        PaintButton(OrderButton, true);

        var totalColor = total < DeliveryRules.MinOrderTotal || total > _balance ? "#E06060" : "#80E080";
        CartSummary.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("delivery-ui-cart-summary",
            ("count", itemCount),
            ("max", DeliveryRules.MaxItems),
            ("total", YupiRules.FormatCredits(total)),
            ("min", YupiRules.FormatCredits(DeliveryRules.MinOrderTotal)),
            ("color", totalColor))));
    }

    private readonly record struct CatalogItem(string Prototype, string Name, int Price, int Section);

    private sealed class CatalogRow
    {
        public readonly PanelContainer Root;
        public readonly Button Minus;
        public readonly Button Plus;
        public readonly Label Count;

        public CatalogRow(CatalogItem item, Color background)
        {
            var view = new EntityPrototypeView { SetSize = new Vector2(32, 32) };
            var name = new MarqueeLabel
            {
                Text = item.Name,
                IdleAlign = Label.AlignMode.Left,
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(4, 0),
            };
            view.SetPrototype(item.Prototype);

            Minus = new Button { Text = "-", MinWidth = 24 };
            Plus = new Button { Text = "+", MinWidth = 24 };
            Count = new Label { Text = "0", MinWidth = 24, Align = Label.AlignMode.Center };

            var content = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(2, 1),
                Children =
                {
                    view,
                    name,
                    new Label
                    {
                        Text = Loc.GetString("delivery-ui-price", ("amount", YupiRules.FormatCredits(item.Price))),
                        VerticalAlignment = VAlignment.Center,
                        Align = Label.AlignMode.Right,
                        MinWidth = 90,
                        Margin = new Thickness(4, 0),
                    },
                    Minus,
                    Count,
                    Plus,
                },
            };

            Root = new PanelContainer
            {
                HorizontalExpand = true,
                MouseFilter = MouseFilterMode.Pass,
                PanelOverride = new StyleBoxFlat { BackgroundColor = background },
            };
            Root.OnMouseEntered += _ => name.Hovered = true;
            Root.OnMouseExited += _ => name.Hovered = false;
            Root.AddChild(content);
        }
    }

    #endregion

    #region Courier

    private void UpdateCourier(DeliveryUiState state)
    {
        CourierNameLabel.Text = state.CourierName;
        CourierStatsLabel.Text = Loc.GetString("delivery-ui-courier-stats",
            ("delivered", state.Delivered),
            ("earned", YupiRules.FormatCredits(state.Earned)));
        CourierBalanceLabel.Text = state.Balance is { } balance
            ? Loc.GetString("delivery-ui-balance", ("amount", YupiRules.FormatCredits(balance)))
            : Loc.GetString("delivery-ui-cash-payout");

        var mine = state.Orders.Count(o => o.TakenByViewer);
        CourierStatsLabel.Text += Environment.NewLine + Loc.GetString("delivery-ui-courier-active", ("count", mine), ("max", DeliveryRules.MaxCourierOrders));

        var signature = string.Join(';', state.Orders.Select(o => $"{o.Id}|{o.Courier}|{o.TakenByViewer}|{o.InTransit}"));
        if (signature == _courierSignature)
        {
            foreach (var order in state.Orders)
            {
                if (_positionLabels.TryGetValue(order.Id, out var label))
                    label.Text = FormatPosition(order.Position, order.InTransit);
            }

            return;
        }

        _courierSignature = signature;
        _timers.Clear();
        _positionLabels.Clear();
        CourierOrdersList.RemoveAllChildren();
        NoCourierOrdersLabel.Visible = state.Orders.Count == 0;
        foreach (var order in state.Orders)
        {
            CourierOrdersList.AddChild(BuildOrderCard(order, true));
        }
    }

    private static string FormatPosition(Vector2? position, bool inTransit)
    {
        if (!inTransit)
            return Loc.GetString("delivery-ui-order-position-pending");

        return position is { } pos
            ? Loc.GetString("delivery-ui-order-position", ("x", (int) MathF.Round(pos.X)), ("y", (int) MathF.Round(pos.Y)))
            : Loc.GetString("delivery-ui-order-position-unknown");
    }

    #endregion

    private Control BuildOrderCard(DeliveryOrderInfo order, bool courierView)
    {
        var box = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(6, 4),
        };

        box.AddChild(new Label
        {
            Text = Loc.GetString("delivery-ui-order-title", ("id", order.Id), ("customer", order.Customer)),
            FontColorOverride = AccentColor,
        });

        string status;
        if (order.Courier == null)
            status = Loc.GetString(order.InTransit ? "delivery-ui-status-reassign" : "delivery-ui-status-waiting");
        else if (order.TakenByViewer)
            status = Loc.GetString("delivery-ui-status-yours");
        else
            status = Loc.GetString(courierView ? "delivery-ui-status-taken" : "delivery-ui-status-in-transit", ("courier", order.Courier));
        box.AddChild(new Label { Text = status });

        box.AddChild(new Label
        {
            Text = courierView
                ? Loc.GetString("delivery-ui-order-money-courier",
                    ("total", YupiRules.FormatCredits(order.Total)),
                    ("payout", YupiRules.FormatCredits(order.Payout)))
                : Loc.GetString("delivery-ui-order-money", ("total", YupiRules.FormatCredits(order.Total))),
        });

        var timer = new Label();
        _timers.Add((timer, order.ExpiresAt));
        box.AddChild(timer);

        if (courierView)
        {
            var position = new Label { Text = FormatPosition(order.Position, order.InTransit) };
            _positionLabels[order.Id] = position;
            box.AddChild(position);
        }

        var items = new RichTextLabel { HorizontalExpand = true };
        items.SetMessage(FormattedMessage.FromMarkupOrThrow(
            $"[color={HintColor.ToHex()}]{FormattedMessage.EscapeText(BuildItemsSummary(order.Items))}[/color]"));
        box.AddChild(items);

        if (courierView && order.Courier == null && !order.TakenByViewer)
        {
            var take = new Button
            {
                Text = Loc.GetString("delivery-ui-take"),
                HorizontalAlignment = HAlignment.Right,
            };
            var id = order.Id;
            take.OnPressed += _ => OnTake?.Invoke(id);
            PaintButton(take, true);
            box.AddChild(take);
        }

        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 2),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = CardColor,
                BorderColor = AccentColor,
                BorderThickness = new Thickness(3, 0, 0, 0),
            },
        };
        panel.AddChild(box);
        return panel;
    }

    private string BuildItemsSummary(List<DeliveryOrderItem> items)
    {
        var parts = new List<string>();
        foreach (var item in items.Take(SummaryItems))
        {
            var name = _proto.TryIndex<EntityPrototype>(item.Prototype, out var proto) ? proto.Name : item.Prototype;
            parts.Add(Loc.GetString("delivery-ui-item", ("name", name), ("count", item.Count)));
        }

        var summary = string.Join(", ", parts);
        if (items.Count > SummaryItems)
            summary += Loc.GetString("delivery-ui-items-more", ("count", items.Count - SummaryItems));

        return summary;
    }

    private void UpdateTimers()
    {
        var now = _timing.CurTime;
        foreach (var (label, expiresAt) in _timers)
        {
            var left = expiresAt - now;
            if (left < TimeSpan.Zero)
                left = TimeSpan.Zero;

            label.Text = Loc.GetString("delivery-ui-time-left", ("time", $"{(int) left.TotalMinutes:D2}:{left.Seconds:D2}"));
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_timers.Count == 0)
            return;

        var second = (int) _timing.CurTime.TotalSeconds;
        if (second == _shownSecond)
            return;

        _shownSecond = second;
        UpdateTimers();
    }
