using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.PDV.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls; // LuaM
using Content.Client.Message; // LuaM
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Mono.PDV.UI;

[GenerateTypedNameReferences]
public sealed partial class HereticMenu : FancyWindow
{
    public HereticMenu()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateEntries(List<Heretic> heretics)
    {
        HereticEntriesContainer.Children.Clear();

        // LuaM-start: say so when nobody is hunted
        if (heretics.Count == 0)
        {
            var empty = new RichTextLabel
            {
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(10, 20, 10, 0),
            };
            empty.SetMarkup(Loc.GetString("pdv-heretic-console-empty"));
            HereticEntriesContainer.AddChild(empty);
            return;
        }
        // LuaM-end

        foreach (var h in heretics)
        {
            var entry = new HereticEntry(h);

            HereticEntriesContainer.AddChild(entry);
        }
        HereticEntriesContainer.AddChild(new Control
        {
            MinHeight = 10
        });
    }
}
