using Content.Client.Message;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.AutoGenerated;
using Content.Shared._Mono.PDV.Components;
using Content.Shared._NF.Bank; // LuaM
using Robust.Shared.Utility; // LuaM

namespace Content.Client._Mono.PDV.UI;

[GenerateTypedNameReferences]
public sealed partial class HereticEntry : BoxContainer
{
    public HereticEntry(Heretic heretic)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // LuaM-start: a wanted notice, not the smuggling bounty manifest
        ManifestLabel.SetMarkup(Loc.GetString("pdv-heretic-console-target-label",
            ("name", FormattedMessage.EscapeText(heretic.Name))));
        RewardLabel.SetMarkup(Loc.GetString("pdv-heretic-console-reward-label",
            ("reward", BankSystemExtensions.ToIndependentString(heretic.Reward))));
        // LuaM-end
        DescriptionLabel.SetMarkup(Loc.GetString("pdv-heretic-console-description"));
    }
}
