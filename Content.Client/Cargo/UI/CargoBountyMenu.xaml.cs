using Content.Client.UserInterface.Controls;
using Content.Shared.Cargo;
using Content.Shared._LuaM.Cargo; // LuaM
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Cargo.UI;

[GenerateTypedNameReferences]
public sealed partial class CargoBountyMenu : FancyWindow
{
    public Action<string>? OnLabelButtonPressed;
    public Action<string>? OnSkipButtonPressed;

    private string? _localePrefix; // LuaM

    public CargoBountyMenu()
    {
        RobustXamlLoader.Load(this);

        MasterTabContainer.SetTabTitle(0, Loc.GetString("bounty-console-tab-available-label"));
        MasterTabContainer.SetTabTitle(1, Loc.GetString("bounty-console-tab-history-label"));
    }

    // LuaM-start: texts of a console with its own locale prefix
    public void SetLocalePrefix(string? prefix)
    {
        _localePrefix = prefix;
        Title = BountyConsoleLoc.Get(prefix, "bounty-console-menu-title");
        MasterTabContainer.SetTabTitle(0, BountyConsoleLoc.Get(prefix, "bounty-console-tab-available-label"));
        MasterTabContainer.SetTabTitle(1, BountyConsoleLoc.Get(prefix, "bounty-console-tab-history-label"));
        NoHistoryLabel.Text = BountyConsoleLoc.Get(prefix, "bounty-console-history-empty-label");
        FlavorLeftLabel.Text = BountyConsoleLoc.Get(prefix, "bounty-console-flavor-left");
        FlavorRightLabel.Text = BountyConsoleLoc.Get(prefix, "bounty-console-flavor-right");
    }
    // LuaM-end

    public void UpdateEntries(List<CargoBountyData> bounties, List<CargoBountyHistoryData> history, TimeSpan untilNextSkip)
    {
        BountyEntriesContainer.Children.Clear();
        foreach (var b in bounties)
        {
            var entry = new BountyEntry(b, untilNextSkip, _localePrefix); // LuaM: prefix
            entry.OnLabelButtonPressed += () => OnLabelButtonPressed?.Invoke(b.Id);
            entry.OnSkipButtonPressed += () => OnSkipButtonPressed?.Invoke(b.Id);

            BountyEntriesContainer.AddChild(entry);
        }
        BountyEntriesContainer.AddChild(new Control
        {
            MinHeight = 10
        });

        BountyHistoryContainer.Children.Clear();
        if (history.Count == 0)
        {
            NoHistoryLabel.Visible = true;
        }
        else
        {
            NoHistoryLabel.Visible = false;

            // Show the history in reverse, so last entry is first in the list
            for (var i = history.Count - 1; i >= 0; i--)
            {
                BountyHistoryContainer.AddChild(new BountyHistoryEntry(history[i], _localePrefix)); // LuaM: prefix
            }
        }
    }
}
