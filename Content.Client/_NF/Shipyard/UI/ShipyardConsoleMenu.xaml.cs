    /// <summary>
    /// Given a set of prototype IDs, returns a corresponding set of prototypes, ordered by name.
    /// </summary>
    private List<VesselPrototype> GetVesselPrototypesFromIds(IEnumerable<string> protoIds) // Lua: VesselPrototype? > VesselPrototype
    {
        var vesselList = protoIds.Select(it => _protoManager.TryIndex<VesselPrototype>(it, out var proto) ? proto : null)
            .OfType<VesselPrototype>() // Lua: Where(it => it != null) > OfType
            .ToList();

        vesselList.Sort((x, y) =>
            string.Compare(GetLocalizedVesselName(x), GetLocalizedVesselName(y), StringComparison.CurrentCultureIgnoreCase)); // Lua: Name > GetLocalizedVesselName
        return vesselList;
    }

    /// <summary>
    /// Adds all vessels in a given list of prototypes as VesselRows in the UI.
    /// </summary>
    private void AddVesselsToControls(IEnumerable<VesselPrototype> vessels, string search, bool free, bool canPurchase)
    {
        foreach (var prototype in vessels)
        {
            // Filter any ships
            if (_category != null && !prototype.Category.Equals(_category))
                continue;
            if (_class != null && !prototype.Classes.Contains(_class.Value))
                continue;
            if (_engine != null && !prototype.Engines.Contains(_engine.Value))
                continue;
// LuaM-start:
            if (search.Length > 0)
            {
                var localizedName = GetLocalizedVesselName(prototype).ToLowerInvariant();
                var protoId = prototype.ID.ToLowerInvariant();

                if (!localizedName.Contains(search) && !protoId.Contains(search))
                    continue;
            }
// LuaM-end.
            // LuaM start: the row only selects a vessel; price, limits and purchase are shown for the selection
            var (limit, limitRemain) = GetLimit(prototype);
            var vesselEntry = new VesselRow
            {
                Vessel = prototype,
                VesselName = { Text = GetLocalizedVesselName(prototype) },
                CategoryLabel = { Text = Loc.GetString($"shipyard-console-category-{prototype.Category}") },
                LimitedCount = { Visible = limit > 0, Text = $"{Math.Max(limitRemain, 0)}/{limit}" },
                Pressed = prototype.ID == _selected?.ID,
            };
            vesselEntry.OnPressed += _ => Select(prototype);
            Vessels.AddChild(vesselEntry);
            // LuaM end
        }
    }

    // LuaM start
    private (int Limit, int Remain) GetLimit(VesselPrototype prototype)
    {
        var limit = _hyperwarLimits ? prototype.HyperwarLimitActive : prototype.LimitActive;
        return (limit, limit - _limitedCounts.GetValueOrDefault((ProtoId<VesselPrototype>) prototype.ID));
    }

    private string GetPriceText(VesselPrototype prototype)
    {
        if (_freeListings)
            return Loc.GetString("shipyard-console-menu-listing-free");

        if (!prototype.Purchasable)
            return Loc.GetString("shipyard-console-menu-listing-voucher");

        return BankSystemExtensions.ToSpesoString(prototype.Price);
    }

    private string GetStockText(VesselPrototype prototype)
    {
        var (limit, remain) = GetLimit(prototype);
        return limit > 0
            ? Loc.GetString("shipyard-info-stock-limited", ("remain", Math.Max(remain, 0)), ("limit", limit))
            : Loc.GetString("shipyard-info-stock-unlimited");
    }

    /// <summary>
    /// Selects a vessel: shows its preview and data, and arms the purchase button for it.
    /// </summary>
    private void Select(VesselPrototype prototype)
    {
        if (_selected?.ID != prototype.ID)
            PurchaseButton.ClearIsConfirming();

        _selected = prototype;
        foreach (var child in Vessels.Children)
        {
            if (child is VesselRow row)
                row.Pressed = row.Vessel?.ID == prototype.ID;
        }

        PreviewView.SetVessel(prototype);
        RefreshSelection();
    }

    private void RefreshSelection()
    {
        var vessel = _selected;
        InfoGrid.RemoveAllChildren();
        LayoutGrid.RemoveAllChildren();

        if (vessel == null)
        {
            PreviewTitle.Text = string.Empty;
            PreviewSubtitle.Text = string.Empty;
            PreviewStatus.Text = Loc.GetString("shipyard-preview-select");
            PreviewStatusPanel.Visible = true;
            InfoName.Text = string.Empty;
            InfoSize.Text = string.Empty;
            InfoDescription.SetMessage(new FormattedMessage());
            SelectedPriceLabel.Text = Loc.GetString("shipyard-info-unknown");
            PurchaseButton.Disabled = true;
            return;
        }

        var name = GetLocalizedVesselName(vessel);
        var size = Loc.GetString($"shipyard-console-category-{vessel.Category}");
        var stock = GetStockText(vessel);
        var price = GetPriceText(vessel);
        var entry = PreviewView.Entry;
        var info = entry?.Info;

        PreviewTitle.Text = name;
        PreviewSubtitle.Text = Loc.GetString("shipyard-preview-subtitle", ("size", size), ("stock", stock));
        PreviewStatus.Text = PreviewView.Loading
            ? Loc.GetString("shipyard-preview-loading")
            : entry is { Failed: true }
                ? Loc.GetString("shipyard-preview-failed")
                : string.Empty;
        PreviewStatusPanel.Visible = PreviewStatus.Text.Length > 0;

        InfoName.Text = name;
        InfoSize.Text = size;
        AddInfoRow(InfoGrid, "shipyard-info-price", price);
        AddInfoRow(InfoGrid, "shipyard-info-size", size);
        AddInfoRow(InfoGrid, "shipyard-info-class", string.Join(" / ", vessel.Classes
            .Where(c => c != VesselClass.All)
            .Select(c => Loc.GetString($"shipyard-console-class-{c}"))));
        AddEngineRow(vessel);
        AddInfoRow(InfoGrid, "shipyard-info-stock", stock);
        InfoDescription.SetMessage(FormattedMessage.FromUnformatted(GetLocalizedVesselDescription(vessel)));

        AddInfoRow(LayoutGrid, "shipyard-info-dimensions", info != null
            ? Loc.GetString("shipyard-info-dimensions-value", ("width", info.Dimensions.X), ("height", info.Dimensions.Y))
            : Loc.GetString("shipyard-info-unknown"));
        AddInfoRow(LayoutGrid, "shipyard-info-deck", info != null
            ? Loc.GetString("shipyard-info-deck-value", ("tiles", info.Tiles))
            : Loc.GetString("shipyard-info-unknown"));

        var (limit, remain) = GetLimit(vessel);
        var available = _lastAvailableProtos.Contains(vessel.ID);
        PurchaseButton.Disabled = _guidebookReadOnly || !available || !_validId || limit > 0 && remain <= 0;
        SelectedPriceLabel.Text = price;
    }

    /// <summary>
    /// Power types with a small icon of their fuel or generator next to the name.
    /// </summary>
    private void AddEngineRow(VesselPrototype vessel)
    {
        var engines = vessel.Engines.Where(e => e != VesselEngine.All).Distinct().ToList();
        if (engines.Count == 0)
            return;

        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
        row.AddChild(new Label
        {
            Text = Loc.GetString("shipyard-info-engine"),
            FontColorOverride = InfoKeyColor,
            MinWidth = 120,
            VerticalAlignment = VAlignment.Top,
        });

        var values = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        foreach (var engine in engines)
        {
            var item = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            if (EngineIcons.TryGetValue(engine, out var icon) && _protoManager.TryIndex(icon, out var proto))
            {
                item.AddChild(new TextureRect
                {
                    Texture = _sprite.Frame0(proto),
                    SetSize = new Vector2(24, 24),
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                    VerticalAlignment = VAlignment.Center,
                });
            }

            item.AddChild(new Label
            {
                Text = Loc.GetString($"shipyard-console-engine-{engine}"),
                VerticalAlignment = VAlignment.Center,
            });
            values.AddChild(item);
        }

        row.AddChild(values);
        InfoGrid.AddChild(row);
    }

    private static void AddInfoRow(BoxContainer box, string key, string value)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true };
        row.AddChild(new Label
        {
            Text = Loc.GetString(key),
            FontColorOverride = InfoKeyColor,
            MinWidth = 120,
            VerticalAlignment = VAlignment.Top,
        });

        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(FormattedMessage.FromUnformatted(value));
        row.AddChild(label);
        box.AddChild(row);
    }

    /// <summary>
    /// Shrinks the window to the screen before it opens; OpenCentered measures it beforehand.
    /// </summary>
    private void FitToScreen()
    {
        // -- Окно рассчитано на большой экран: на маленьком ужимаем до 95% области, иначе края уходят за экран
        var available = UserInterfaceManager.RootControl.Size * 0.95f;
        if (available.X <= 0 || available.Y <= 0)
            return;

        MinSize = Vector2.Min(MinSize, available);
        SetSize = Vector2.Min(SetSize, available);
    }
