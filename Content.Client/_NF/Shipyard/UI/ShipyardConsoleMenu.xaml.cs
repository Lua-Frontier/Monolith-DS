    /// <summary>
    /// Selects the docking port closest to the click, or clears the selection when clicking the selected one or empty space.
    /// </summary>
    private void OnDockRadarClick(EntityCoordinates coords)
    {
        if (_dockNav == null)
            return;

        var clickMapPos = _xform.ToMapCoordinates(coords).Position;
        NetEntity? best = null;
        var bestDistSq = float.MaxValue;

        foreach (var ports in _dockNav.Docks.Values)
        {
            foreach (var port in ports)
            {
                var portCoords = _entManager.GetCoordinates(port.Coordinates);
                if (!portCoords.IsValid(_entManager))
                    continue;

                var distSq = (_xform.ToMapCoordinates(portCoords).Position - clickMapPos).LengthSquared();
                if (distSq >= bestDistSq)
                    continue;

                bestDistSq = distSq;
                best = port.Entity;
            }
        }

        if (best == null || bestDistSq > MaxDockPickDistance * MaxDockPickDistance || best == _selectedDockPort)
            best = null;

        _selectedDockPort = best;
        DockRadar.HighlightDockPort = best;
        OnDockPortSelected?.Invoke(best);
    }
