using Content.Shared.Shuttles.BUIStates;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Content.Client.Stylesheets; // LuaM

namespace Content.Client.Shuttles.UI;

[GenerateTypedNameReferences]
public sealed partial class DockObject : PanelContainer
{
    public BoxContainer ContentsContainer => Contents;

    public DockObject()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

//        PanelOverride = new StyleBoxFlat(new Color(30, 30, 34)); // Commented by LuaM
        AddStyleClass(ConsoleStyles.Inset); // LuaM
    }

    public void AddDock(DockingPortState state, ShuttleDockControl dockControl)
    {
        var dockLabel = new Label()
        {
            Text = Loc.GetString("luam-shuttle-dock-external-airlock"), // LuaM: "external airlock" > luam-shuttle-dock-external-airlock
            HorizontalAlignment = HAlignment.Center,
        };
        
        var viewButton = new Button()
        {
            Text = Loc.GetString("luam-shuttle-dock-view"), // LuaM: "View" > luam-shuttle-dock-view
            StyleClasses = { ConsoleStyles.Button }, // LuaM
        };

        viewButton.OnPressed += args =>
        {
            dockControl.SetViewedDock(state);
        };

        var container = new BoxContainer()
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Children =
            {
                dockLabel,
                viewButton
            }
        };

        DockContainer.AddChild(container);
    }

    public void SetName(string value)
    {
        DockedLabel.Text = value;
    }
}
